const FONT = 'Times New Roman';
const CM = 567; // twips per cm
const LINE = 360; // 1.5 lines
const TEXT_WIDTH = 10772; // 210 - 30 - 10 = 170 mm in twips (approx.)
const PX_PER_CM = 37.8;

const run = (text, o = {}) => new TextRun({ text, font: FONT, size: (o.size ?? 14) * 2, italics: o.italics, bold: o.bold });

function p(text, o = {}) {
  return new Paragraph({
    alignment: o.align ?? AlignmentType.JUSTIFIED,
    indent: { firstLine: o.noIndent ? 0 : 1.25 * CM },
    spacing: { line: o.line ?? LINE, before: o.before ?? 0, after: o.after ?? 0 },
    keepNext: o.keepNext,
    children: Array.isArray(text) ? text : [run(text, o)],
  });
}
const empty = () => p('', { noIndent: true });

function h1(text, o = {}) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.CENTER,
    pageBreakBefore: o.pageBreak !== false,
    spacing: { line: LINE, before: 0, after: LINE },
    keepNext: true,
    children: [run(text, { bold: true })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE, before: LINE, after: LINE },
    keepNext: true,
    children: [run(text, { bold: true })],
  });
}

function list(items, ordered = false) {
  return items.map((t) => new Paragraph({
    numbering: { reference: ordered ? 'num' : 'dash', level: 0 },
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: LINE },
    children: [run(t)],
  }));
}
let numInstance = 0;
function olist(items) {
  numInstance += 1;
  const ref = numInstance;
  return items.map((t) => new Paragraph({
    numbering: { reference: 'num', level: 0, instance: ref },
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: LINE },
    children: [run(t)],
  }));
}

function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), data: b };
}
function image(file, widthCm, maxHeightCm = 23) {
  const { w, h, data } = pngSize(file);
  let wpx = widthCm * PX_PER_CM;
  let hpx = (wpx * h) / w;
  const maxH = maxHeightCm * PX_PER_CM;
  if (hpx > maxH) { hpx = maxH; wpx = (hpx * w) / h; }
  return new ImageRun({ type: 'png', data, transformation: { width: Math.round(wpx), height: Math.round(hpx) } });
}
function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE, before: 0, after: LINE },
    children: [run(text)],
  });
}
function fig(file, widthCm, cap, maxHeightCm) {
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, keepNext: true, spacing: { line: 240, before: 120 }, children: [image(file, widthCm, maxHeightCm)] }),
    caption(cap),
  ];
}
const NONE = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
const noBorders = { top: NONE, bottom: NONE, left: NONE, right: NONE, insideHorizontal: NONE, insideVertical: NONE };
/** Two (or three) phone screenshots side by side with «а) … б) …» labels. */
function figRow(items, cap, widthCm = 5.0) {
  const colW = Math.floor(TEXT_WIDTH / items.length);
  const cell = ([file, label]) => new TableCell({
    width: { size: colW, type: WidthType.DXA },
    borders: { top: NONE, bottom: NONE, left: NONE, right: NONE },
    children: [
      new Paragraph({ alignment: AlignmentType.CENTER, children: [image(file, widthCm)] }),
      new Paragraph({ alignment: AlignmentType.CENTER, spacing: { line: 240, before: 60 }, children: [run(label, { size: 12 })] }),
    ],
  });
  return [
    new Table({
      width: { size: TEXT_WIDTH, type: WidthType.DXA },
      columnWidths: items.map(() => colW),
      borders: noBorders,
      rows: [new TableRow({ cantSplit: true, children: items.map(cell) })],
    }),
    caption(cap),
  ];
}

const B = { style: BorderStyle.SINGLE, size: 4, color: '000000' };
const borders = { top: B, bottom: B, left: B, right: B };
function tableTitle(text) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { firstLine: 1.25 * CM },
    spacing: { line: LINE, before: 120, after: 60 },
    keepNext: true,
    children: [run(text)],
  });
}
/** Table with 12 pt text; widths in cm (scaled to the text width). */
function table(header, rows, widthsCm) {
  const total = widthsCm.reduce((a, b) => a + b, 0);
  const widths = widthsCm.map((w) => Math.floor((w / total) * TEXT_WIDTH));
  const mk = (cells, isHeader) => new TableRow({
    tableHeader: isHeader,
    cantSplit: true,
    children: cells.map((c, i) => new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      borders,
      verticalAlign: VerticalAlign.TOP,
      margins: { top: 30, bottom: 30, left: 80, right: 80 },
      children: String(c).split('\n').map((line) => new Paragraph({
        alignment: isHeader ? AlignmentType.CENTER : AlignmentType.LEFT,
        spacing: { line: 240 },
        children: [run(line, { size: 12 })],
      })),
    })),
  });
  return [
    new Table({
      width: { size: TEXT_WIDTH, type: WidthType.DXA },
      columnWidths: widths,
      layout: TableLayoutType.FIXED,
      rows: [mk(header, true), ...rows.map((r) => mk(r, false))],
    }),
    new Paragraph({ spacing: { line: 240, after: 120 }, children: [] }),
  ];
}
function code(lines) {
  return lines.map((l) => new Paragraph({
    spacing: { line: 240 },
    children: [new TextRun({ text: l.replace(/ /g, ' '), font: 'Courier New', size: 20 })],
  }));
}

